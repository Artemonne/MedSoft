import { Router } from 'express';
import { ServiceAccountRole } from '@prisma/client';
import { serviceAuthController } from '../controllers/service-auth.js';
import { asyncHandler } from '../lib/async-handler.js';
import { authenticateServiceAccessToken, authorizeServiceRole } from '../middleware/authenticate-service.js';
export const serviceAuthRouter = Router();
serviceAuthRouter.post('/token', asyncHandler(serviceAuthController.token));
serviceAuthRouter.post('/refresh', asyncHandler(serviceAuthController.refresh));
serviceAuthRouter.post('/logout', asyncHandler(authenticateServiceAccessToken), authorizeServiceRole(ServiceAccountRole.LIS), asyncHandler(serviceAuthController.logout));
serviceAuthRouter.get('/test-connection', asyncHandler(authenticateServiceAccessToken), authorizeServiceRole(ServiceAccountRole.LIS), asyncHandler(serviceAuthController.testConnection));
